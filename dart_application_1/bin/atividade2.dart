void main() {
  // Declarando as variáveis
  int numero1 = 35; 
  int numero2 = 20;

  // Apresentando os números 
  print ('Número 1: $numero1 \nNúmero 2: $numero2.');

  // Adição
  print ('A soma de $numero1 + $numero2 é: ${numero1 + numero2}.');

  // Subtração
  print ('A subtração de $numero1 - $numero2 é: ${numero1 - numero2}.');

  // Multiplicação
  print ('A multiplicação de $numero1 * $numero2 é: ${numero1 * numero2}.');

  // Divisão
  print ('A divisão de $numero1 por $numero2 é: ${numero1 / numero2}.');

  // Resto da divisão
  print ('O resto da divisão de $numero1 por $numero2 é: ${numero1 % numero2}.');
}